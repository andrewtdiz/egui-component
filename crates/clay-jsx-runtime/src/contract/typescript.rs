fn emit_family_types(
    out: &mut String,
    all_families: &[ContractFamilySpec],
    node_common: &ContractSharedTypeSpec,
    shared_type_names: &BTreeSet<String>,
) {
    for family in all_families {
        let family_name = family.id.as_str();
        let family_type_name = family_props_type_name(family_name);
        let family_base_type_name = format!("{family_type_name}Base");

        out.push_str(&format!("interface {family_base_type_name} {{\n"));
        out.push_str(&format!("  readonly \"data-slot\"?: \"{family_name}\";\n"));
        out.push_str(&format!("  readonly dataSlot?: \"{family_name}\";\n"));
        out.push_str("  readonly role?: string;\n");
        out.push_str("  readonly type?: string;\n");

        if family.includes_common_props {
            emit_props(
                out,
                node_common.fields,
                shared_type_names,
                EmitMode::AllOptional,
                true,
            );
        }
        emit_props(
            out,
            family.props,
            shared_type_names,
            EmitMode::AllOptional,
            true,
        );

        let mut handler_names = BTreeSet::new();
        handler_names.insert("onEvent");
        for event in family.events {
            for handler_name in event_handler_names(event.kind) {
                handler_names.insert(handler_name);
            }
        }
        for handler_name in handler_names {
            out.push_str(&format!("  readonly {handler_name}?: ClayEventHandler;\n"));
        }

        out.push_str("}\n");
        if family.id.requires_explicit_node_id() {
            out.push_str(&format!(
                "type {family_type_name} = {family_base_type_name} & ClayIdentityNodeId;\n\n"
            ));
        } else {
            out.push_str(&format!(
                "type {family_type_name} = {family_base_type_name};\n\n"
            ));
        }
    }

    out.push_str("interface ClayFamilyPropsMap {\n");
    for family in all_families {
        let family_name = family.id.as_str();
        let family_type_name = family_props_type_name(family_name);
        out.push_str(&format!(
            "  readonly \"{family_name}\": {family_type_name};\n"
        ));
    }
    out.push_str("}\n\n");

    out.push_str("type ClayAnyFamilyProps = ClayFamilyPropsMap[ClayContractFamily];\n\n");
}

fn emit_intrinsic_types(out: &mut String, all_families: &[ContractFamilySpec]) {
    out.push_str("type ClaySlotOverrideProps = { readonly \"data-slot\": ClayContractFamily } & ClayAnyFamilyProps;\n\n");

    out.push_str("interface ClayIntrinsicElements {\n");
    let mut claimed_names = BTreeSet::new();
    for family in all_families {
        let family_name = family.id.as_str();
        if HTML_HOST_TAGS.contains(&family_name) {
            continue;
        }
        let family_type_name = family_props_type_name(family_name);
        out.push_str(&format!(
            "  readonly \"{family_name}\": {family_type_name};\n"
        ));
        claimed_names.insert(family_name.to_owned());
    }

    for (alias_name, family_name) in LEGACY_FAMILY_ALIASES {
        if claimed_names.contains(alias_name) {
            continue;
        }
        let family_type_name = family_props_type_name(family_name);
        out.push_str(&format!(
            "  readonly \"{alias_name}\": {family_type_name};\n"
        ));
        claimed_names.insert(alias_name.to_owned());
    }

    for tag in HTML_HOST_TAGS {
        if claimed_names.contains(tag) {
            continue;
        }
        let tag_type = html_tag_type(tag);
        out.push_str(&format!("  readonly \"{tag}\": {tag_type};\n"));
        claimed_names.insert(tag.to_owned());
    }

    out.push_str("}\n\n");
}

