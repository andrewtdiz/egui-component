pub fn typescript_declarations() -> String {
    let all_families = registry();
    let all_shared_types = shared_types();
    let node_common = all_shared_types
        .iter()
        .find(|shared| shared.name == "node_common")
        .expect("node_common shared type should exist");

    let shared_type_names = all_shared_types
        .iter()
        .map(|shared| shared.name.to_owned())
        .collect::<BTreeSet<_>>();

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p clay-jsx-runtime --bin generate-contract-types`\n",
    );
    out.push_str("// Do not edit by hand.\n\n");
    out.push_str("/* eslint-disable */\n\n");

    out.push_str(&format!(
        "type ClayContractModelVersion = {CONTRACT_MODEL_VERSION};\n"
    ));
    out.push_str(&format!(
        "type ClayContractSchemaFingerprint = \"{}\";\n\n",
        schema_fingerprint()
    ));

    out.push_str("type ClayContractFamily =\n");
    for family in all_families {
        out.push_str(&format!("  | \"{}\"\n", family.id.as_str()));
    }
    out.push_str(";\n\n");

    emit_shared_types(&mut out, all_shared_types, &shared_type_names);
    emit_event_support_types(&mut out);
    emit_family_types(&mut out, all_families, node_common, &shared_type_names);
    emit_intrinsic_types(&mut out, all_families);
    emit_runtime_module_declarations(&mut out, all_families);

    out
}

pub fn write_typescript_declarations(path: impl AsRef<Path>) -> std::io::Result<()> {
    let path = path.as_ref();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, typescript_declarations())
}

fn emit_shared_types(
    out: &mut String,
    all_shared_types: &[ContractSharedTypeSpec],
    shared_type_names: &BTreeSet<String>,
) {
    out.push_str("type ClayNode = import(\"react\").ReactNode;\n");
    out.push_str("type ClayRecord = Readonly<Record<string, unknown>>;\n\n");

    for shared in all_shared_types {
        let shared_type_name = shared_type_ts_name(shared.name);
        match shared.kind {
            ContractSharedTypeKind::Enum => {
                if shared.variants.is_empty() {
                    out.push_str(&format!("type {shared_type_name} = string;\n\n"));
                    continue;
                }
                out.push_str(&format!("type {shared_type_name} =\n"));
                for variant in shared.variants {
                    out.push_str(&format!("  | \"{}\"\n", variant.id));
                }
                out.push_str(";\n\n");
            }
            ContractSharedTypeKind::Object => {
                out.push_str(&format!("interface {shared_type_name} {{\n"));
                emit_props(
                    out,
                    shared.fields,
                    shared_type_names,
                    EmitMode::SchemaRequired,
                    false,
                );
                out.push_str("}\n\n");
            }
        }
    }
}

