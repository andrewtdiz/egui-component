fn emit_props(
    out: &mut String,
    props: &[ContractPropSpec],
    shared_type_names: &BTreeSet<String>,
    mode: EmitMode,
    include_lowerer_aliases: bool,
) {
    let mut shaped = BTreeMap::new();

    for prop in props {
        let prop_type = prop_type_ts_name(prop, shared_type_names);
        let is_optional = match mode {
            EmitMode::SchemaRequired => !prop.required,
            EmitMode::AllOptional => true,
        };
        merge_prop(
            &mut shaped,
            prop.name.to_owned(),
            prop_type.clone(),
            is_optional,
        );

        let camel_alias = snake_to_camel(prop.name);
        if camel_alias != prop.name {
            merge_prop(&mut shaped, camel_alias, prop_type.clone(), true);
        }
        if include_lowerer_aliases {
            for alias in lowerer_aliases(prop.name) {
                merge_prop(&mut shaped, (*alias).to_owned(), prop_type.clone(), true);
            }
        }
    }

    for (name, prop) in shaped {
        let key = ts_prop_key(&name);
        let optional_marker = if prop.optional { "?" } else { "" };
        out.push_str(&format!(
            "  readonly {key}{optional_marker}: {};\n",
            prop.ty
        ));
    }
}

fn merge_prop(target: &mut BTreeMap<String, TsProp>, name: String, ty: String, optional: bool) {
    if let Some(existing) = target.get_mut(&name) {
        if existing.ty != ty {
            existing.ty = format!("{} | {}", existing.ty, ty);
        }
        existing.optional = existing.optional || optional;
        return;
    }
    target.insert(name, TsProp { ty, optional });
}

fn prop_type_ts_name(prop: &ContractPropSpec, shared_type_names: &BTreeSet<String>) -> String {
    match prop.kind {
        ContractPropTypeKind::String => "string".to_owned(),
        ContractPropTypeKind::StringList => "readonly string[]".to_owned(),
        ContractPropTypeKind::StringMap => "Readonly<Record<string, string>>".to_owned(),
        ContractPropTypeKind::Boolean => "boolean".to_owned(),
        ContractPropTypeKind::Number => "number".to_owned(),
        ContractPropTypeKind::Enum | ContractPropTypeKind::Object => prop
            .type_name
            .map(|type_name| {
                if shared_type_names.contains(type_name) {
                    shared_type_ts_name(type_name)
                } else {
                    "ClayRecord".to_owned()
                }
            })
            .unwrap_or_else(|| "ClayRecord".to_owned()),
        ContractPropTypeKind::ObjectList => prop
            .type_name
            .map(|type_name| {
                let inner = if shared_type_names.contains(type_name) {
                    shared_type_ts_name(type_name)
                } else {
                    "ClayRecord".to_owned()
                };
                format!("readonly {inner}[]")
            })
            .unwrap_or_else(|| "readonly ClayRecord[]".to_owned()),
        ContractPropTypeKind::Node => "ClayNode".to_owned(),
        ContractPropTypeKind::NodeList => "readonly ClayNode[]".to_owned(),
    }
}

fn family_props_type_name(family_name: &str) -> String {
    format!("Clay{}Props", kebab_to_pascal(family_name))
}

fn shared_type_ts_name(type_name: &str) -> String {
    format!("Clay{}", snake_or_kebab_to_pascal(type_name))
}

fn snake_or_kebab_to_pascal(value: &str) -> String {
    value
        .split(['-', '_'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let Some(first) = chars.next() else {
                return String::new();
            };
            let mut out = String::new();
            out.push(first.to_ascii_uppercase());
            out.extend(chars);
            out
        })
        .collect::<String>()
}

fn kebab_to_pascal(value: &str) -> String {
    snake_or_kebab_to_pascal(value)
}

fn snake_to_camel(value: &str) -> String {
    let mut out = String::new();
    let mut uppercase_next = false;
    for ch in value.chars() {
        if ch == '_' {
            uppercase_next = true;
            continue;
        }
        if uppercase_next {
            out.push(ch.to_ascii_uppercase());
            uppercase_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn ts_prop_key(value: &str) -> String {
    if is_ts_identifier(value) {
        value.to_owned()
    } else {
        format!("\"{value}\"")
    }
}

fn is_ts_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return false;
    }
    chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '$')
}

fn html_tag_type(tag: &str) -> String {
    if tag == "input" {
        return "ClayInputProps | ClaySwitchProps | ClayCheckboxProps | ClayRadioProps | ClaySliderProps | ClayNumberInputProps | ClaySlotOverrideProps".to_owned();
    }

    if HTML_CONTAINER_TAGS.contains(&tag) {
        return "ClayRowProps | ClayColumnProps | ClaySlotOverrideProps".to_owned();
    }

    if HTML_TEXT_TAGS.contains(&tag) {
        return "ClayLabelProps | ClaySlotOverrideProps".to_owned();
    }

    if let Some((_, family_name)) = HTML_EXPLICIT_FAMILY_TAGS
        .iter()
        .find(|(html_tag, _)| *html_tag == tag)
    {
        return format!(
            "{} | ClaySlotOverrideProps",
            family_props_type_name(family_name)
        );
    }

    "ClaySlotOverrideProps".to_owned()
}

fn event_handler_names(kind: EventKind) -> &'static [&'static str] {
    match kind {
        EventKind::Clicked => &["onClick"],
        EventKind::Changed => &["onChange", "onInput", "onChanged"],
        EventKind::Submitted => &["onSubmit", "onSubmitted"],
        EventKind::Selected => &["onSelect", "onSelected"],
        EventKind::Toggled => &["onToggle", "onToggled"],
        EventKind::Confirmed => &["onConfirm", "onConfirmed"],
        EventKind::Cancelled => &["onCancel", "onCancelled"],
        EventKind::Opened => &["onOpen", "onOpened"],
        EventKind::Closed => &["onClose", "onClosed"],
        EventKind::CommandInvoked => &["onCommand", "onCommandInvoked"],
    }
}

